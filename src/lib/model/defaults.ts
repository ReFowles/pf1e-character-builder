export const SCHEMA_VERSION = 1;

const ability = (): AbilityScore => ({
  base: 10,
  racial: 0,
  enhancement: 0,
  inherent: 0,
  misc: 0,
  temp: 0,
});

export const coins = (): Coins => ({ pp: 0, gp: 0, sp: 0, cp: 0 });

// Item factories: one per collection so new rows and imported rows share a shape.
